// Build script: extracts stroke paths from KanjiVG SVG files into a compact TS module.
// Usage: `node scripts/build-kanji-data.mjs`
//
// Output: src/data/kanjiPaths.generated.ts
//   - Record<string, string[]> keyed by character
//   - Each value is an ordered array of SVG path `d` attributes (stroke order)
//   - Coordinate system follows KanjiVG: viewBox 0 0 109 109

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const KANJI_DIR = path.join(ROOT, "src/data/kanji");
const OUTPUT_FILE = path.join(ROOT, "src/data/kanjiPaths.generated.ts");

// KanjiVG places only stroke <path> elements inside the `kvg:StrokePaths_*`
// group; the `kvg:StrokeNumbers_*` group is text-only. Matching every <path>
// in document order therefore yields the correct stroke order.
const PATH_D_REGEX = /<path\b[^>]*\sd="([^"]+)"/g;

async function readBaseFiles(dir) {
  const entries = await fs.readdir(dir);
  return entries.filter((f) => /^[0-9a-f]+\.svg$/i.test(f)).sort();
}

function extractStrokePaths(svgText) {
  const paths = [];
  let m;
  PATH_D_REGEX.lastIndex = 0;
  while ((m = PATH_D_REGEX.exec(svgText)) !== null) {
    paths.push(m[1].trim());
  }
  return paths;
}

async function fileExists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  const force = process.argv.includes("--force");
  if (!force && (await fileExists(OUTPUT_FILE))) {
    console.log(
      `Skip: ${path.relative(ROOT, OUTPUT_FILE)} already exists (pass --force to rebuild).`,
    );
    return;
  }

  const files = await readBaseFiles(KANJI_DIR);
  const data = {};

  let skipped = 0;
  for (const file of files) {
    const hex = file.replace(/\.svg$/i, "");
    const codePoint = parseInt(hex, 16);
    if (!Number.isFinite(codePoint)) {
      skipped++;
      continue;
    }
    const char = String.fromCodePoint(codePoint);
    const svg = await fs.readFile(path.join(KANJI_DIR, file), "utf-8");
    const strokes = extractStrokePaths(svg);
    if (strokes.length === 0) {
      skipped++;
      continue;
    }
    data[char] = strokes;
  }

  const json = JSON.stringify(data);
  const content =
    "// AUTO-GENERATED by scripts/build-kanji-data.mjs. Do not edit by hand.\n" +
    "// Source: KanjiVG (https://kanjivg.tagaini.net) - CC BY-SA 3.0\n" +
    "// Each entry maps a character to its KanjiVG stroke `d` attributes in order.\n" +
    "// Coordinate system: viewBox 0 0 109 109.\n\n" +
    "export const KANJIVG_VIEWBOX = 109;\n\n" +
    "export type KanjiStrokes = string[];\n\n" +
    `export const kanjiPaths: Record<string, KanjiStrokes> = ${json};\n`;

  await fs.writeFile(OUTPUT_FILE, content, "utf-8");
  const stat = await fs.stat(OUTPUT_FILE);
  console.log(
    `Wrote ${path.relative(ROOT, OUTPUT_FILE)} | kanji=${
      Object.keys(data).length
    } | skipped=${skipped} | size=${(stat.size / 1024 / 1024).toFixed(2)} MB`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
